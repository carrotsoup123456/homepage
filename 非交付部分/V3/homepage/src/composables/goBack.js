// ======================================================
// 「返回」的统一语义：回到访客来的地方
// ------------------------------------------------------
// 背景：页面里的返回入口如果用 RouterLink push，永远是
// 「导航到列表页顶部」；访客从首页滚到某个位置点进详情页，
// 返回时却被拉回页顶，观感差。
// 这里统一：有来路（vue-router 把来路记在 history.state.back）
// 就调 history.back()——浏览器/微信手势返回是同一语义，
// 滚动位置也由路由的 savedPosition 自动恢复；
// 直接打开分享链接（无来路）才跳指定兜底页。
// ======================================================
export function goBack(router, fallback = '/') {
  if (window.history.state?.back) {
    router.back()
  } else {
    router.push(fallback)
  }
}
